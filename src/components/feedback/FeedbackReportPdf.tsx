import React from "react";
import { Document, Page, Text, View, StyleSheet } from "@react-pdf/renderer";
import type { FeedbackReport, ReportTone } from "@/lib/feedbackReport";
import { reflectionBlocks } from "@/lib/reflectionHtml";

const styles = StyleSheet.create({
  page: {
    padding: 36,
    fontFamily: "Helvetica",
    fontSize: 10,
    color: "#1e293b",
    lineHeight: 1.4,
  },
  title: { fontFamily: "Helvetica-Bold", fontSize: 18, color: "#0f172a", marginBottom: 4 },
  subtitle: { fontSize: 9, color: "#64748b", marginBottom: 16 },
  stats: {
    flexDirection: "row",
    backgroundColor: "#f0fdfa",
    borderWidth: 1,
    borderColor: "#ccfbf1",
    borderRadius: 6,
    padding: 10,
    marginBottom: 16,
  },
  stat: { flex: 1, alignItems: "center" },
  statValue: { fontFamily: "Helvetica-Bold", fontSize: 14, color: "#0f766e" },
  statLabel: { fontSize: 8, color: "#115e59", textTransform: "uppercase", marginTop: 2 },
  row: { flexDirection: "row", gap: 16, marginBottom: 16 },
  column: { flex: 1 },
  columnWide: { flex: 2 },
  sectionTitle: {
    fontFamily: "Helvetica-Bold",
    fontSize: 12,
    color: "#0f172a",
    borderLeftWidth: 3,
    borderLeftColor: "#1fb8cd",
    paddingLeft: 6,
    marginBottom: 8,
  },
  tableHeader: {
    flexDirection: "row",
    borderBottomWidth: 1,
    borderBottomColor: "#cbd5e1",
    paddingBottom: 4,
    marginBottom: 2,
  },
  tableRow: {
    flexDirection: "row",
    borderBottomWidth: 1,
    borderBottomColor: "#e2e8f0",
    paddingVertical: 4,
  },
  cell: { flex: 1, fontSize: 9 },
  cellRight: { width: 90, textAlign: "right", fontFamily: "Helvetica-Bold", color: "#0f766e" },
  headerCell: { flex: 1, fontSize: 8, color: "#64748b", textTransform: "uppercase" },
  headerCellRight: { width: 90, fontSize: 8, color: "#64748b", textAlign: "right", textTransform: "uppercase" },
  summary: {
    backgroundColor: "#f0f9ff",
    borderLeftWidth: 3,
    borderLeftColor: "#3b82f6",
    padding: 8,
    marginBottom: 12,
    fontSize: 10,
    color: "#1e3a8a",
  },
  card: { padding: 6, marginBottom: 6, borderLeftWidth: 3, fontSize: 9 },
  cardGood: { backgroundColor: "#ecfdf5", borderLeftColor: "#10b981" },
  cardImprove: { backgroundColor: "#fffbeb", borderLeftColor: "#f59e0b" },
  cardNeutral: { backgroundColor: "#f8fafc", borderLeftColor: "#cbd5e1" },
  groupTitle: { fontFamily: "Helvetica-Bold", fontSize: 9, marginBottom: 6, textTransform: "uppercase" },
  goodTitle: { color: "#059669" },
  improveTitle: { color: "#d97706" },
  neutralTitle: { color: "#475569" },
  bullet: { fontSize: 10, marginBottom: 3 },
  reflection: {
    backgroundColor: "#fff7ed",
    borderWidth: 1,
    borderColor: "#fed7aa",
    borderRadius: 4,
    padding: 10,
    marginBottom: 12,
  },
  reflectionTitle: { fontFamily: "Helvetica-Bold", fontSize: 12, marginBottom: 6 },
  block: { marginBottom: 12 },
});

const cardStyle = (tone: ReportTone) => {
  if (tone === "good") return styles.cardGood;
  if (tone === "improve") return styles.cardImprove;
  return styles.cardNeutral;
};

const titleStyle = (tone: ReportTone) => {
  if (tone === "good") return styles.goodTitle;
  if (tone === "improve") return styles.improveTitle;
  return styles.neutralTitle;
};

export const FeedbackReportPdf = ({ report }: { report: FeedbackReport }) => {
  const reflection = reflectionBlocks(report.reflection);
  return (
  <Document title={report.docTitle}>
    <Page size="A4" style={styles.page}>
      <Text style={styles.title}>{report.title}</Text>
      <Text style={styles.subtitle}>
        {report.kindLabel} • Generated by Umbil{"\n"}
        Date range: {report.dateRange} • {report.responseCount} responses
      </Text>

      <View style={styles.stats}>
        {report.stats.map((stat) => (
          <View key={stat.label} style={styles.stat}>
            <Text style={styles.statValue}>{stat.value}</Text>
            <Text style={styles.statLabel}>{stat.label}</Text>
          </View>
        ))}
      </View>

      <View style={styles.row}>
        <View style={styles.columnWide}>
          <Text style={styles.sectionTitle}>{report.scoreTitle}</Text>
          <View style={styles.tableHeader}>
            <Text style={styles.headerCell}>Question Area</Text>
            <Text style={styles.headerCellRight}>Average Score</Text>
          </View>
          {report.scoreRows.map((row) => (
            <View key={row.name} style={styles.tableRow}>
              <Text style={styles.cell}>{row.name}</Text>
              <Text style={styles.cellRight}>{row.score}</Text>
            </View>
          ))}
        </View>
        <View style={styles.column}>
          <Text style={styles.sectionTitle}>{report.contextTitle}</Text>
          <View style={styles.tableHeader}>
            <Text style={styles.headerCell}>Type</Text>
            <Text style={styles.headerCellRight}>Count</Text>
          </View>
          {report.contextRows.length === 0 ? (
            <Text style={styles.bullet}>No data recorded</Text>
          ) : (
            report.contextRows.map((row) => (
              <View key={row.name} style={styles.tableRow}>
                <Text style={styles.cell}>{row.name}</Text>
                <Text style={styles.cellRight}>{row.value}</Text>
              </View>
            ))
          )}
        </View>
      </View>

      {report.summary ? (
        <Text style={styles.summary}>Appraisal-Ready Summary: {report.summary}</Text>
      ) : null}

      {report.strengths.length > 0 || report.developmentThemes.length > 0 ? (
        <View style={styles.row}>
          {report.strengths.length > 0 ? (
            <View style={styles.column}>
              <Text style={[styles.groupTitle, styles.goodTitle]}>Top Strengths Identified</Text>
              {report.strengths.map((item, index) => (
                <Text key={`strength-${index}`} style={[styles.card, styles.cardGood]}>{item}</Text>
              ))}
            </View>
          ) : null}
          {report.developmentThemes.length > 0 ? (
            <View style={styles.column}>
              <Text style={[styles.groupTitle, styles.improveTitle]}>Areas for Improvement</Text>
              {report.developmentThemes.map((item, index) => (
                <Text key={`development-${index}`} style={[styles.card, styles.cardImprove]}>{item}</Text>
              ))}
            </View>
          ) : null}
        </View>
      ) : null}

      {report.supportingEvidence.length > 0 ? (
        <View style={styles.block}>
          <Text style={styles.sectionTitle}>Supporting Evidence</Text>
          {report.supportingEvidence.map((item, index) => (
            <Text key={`evidence-${index}`} style={styles.bullet}>• {item}</Text>
          ))}
        </View>
      ) : null}

      {report.gmcRows.length > 0 ? (
        <View style={styles.block}>
          <Text style={styles.sectionTitle}>GMC Domain Mapping</Text>
          <View style={styles.tableHeader}>
            <Text style={styles.headerCell}>Domain</Text>
            <Text style={styles.headerCellRight}>Appraisal Signal</Text>
          </View>
          {report.gmcRows.map((row) => (
            <View key={row.domain} style={styles.tableRow}>
              <Text style={styles.cell}>{row.domain}</Text>
              <Text style={styles.cellRight}>{row.level}</Text>
            </View>
          ))}
        </View>
      ) : null}

      {reflection.length > 0 ? (
        <View style={styles.reflection}>
          <Text style={styles.reflectionTitle}>Appraisal-Ready Reflection</Text>
          {reflection.map((block, index) =>
            block.kind === "list" ? (
              <View key={`reflection-list-${index}`}>
                {block.items.map((item, itemIndex) => (
                  <Text key={`reflection-item-${index}-${itemIndex}`} style={styles.bullet}>
                    {block.ordered ? `${itemIndex + 1}. ` : "• "}
                    {item}
                  </Text>
                ))}
              </View>
            ) : (
              <Text key={`reflection-p-${index}`} style={{ textAlign: block.align, marginBottom: 6 }}>
                {block.text}
              </Text>
            )
          )}
        </View>
      ) : null}

      {report.pdpSuggestions.length > 0 ? (
        <View style={styles.block}>
          <Text style={styles.sectionTitle}>Suggested PDP</Text>
          {report.pdpSuggestions.map((item, index) => (
            <Text key={`pdp-${index}`} style={styles.bullet}>• {item}</Text>
          ))}
        </View>
      ) : null}

      <View style={styles.block}>
        <Text style={styles.sectionTitle}>{report.commentsTitle}</Text>
        {report.commentColumns.length === 0 ? (
          <Text style={styles.bullet}>No written comments available.</Text>
        ) : (
          <View style={styles.row}>
            {report.commentColumns.map((column, columnIndex) => (
              <View key={`comments-${columnIndex}`} style={styles.column}>
                {column.groups.map((group) => (
                  <View key={group.title} style={styles.block}>
                    <Text style={[styles.groupTitle, titleStyle(group.tone)]}>{group.title}</Text>
                    {group.items.map((item, itemIndex) => (
                      <Text key={`${group.title}-${itemIndex}`} style={[styles.card, cardStyle(group.tone)]}>"{item}"</Text>
                    ))}
                  </View>
                ))}
              </View>
            ))}
          </View>
        )}
      </View>

      {report.customFeedback.length > 0 ? (
        <View style={styles.block}>
          <Text style={styles.sectionTitle}>{report.customTitle}</Text>
          {report.customFeedback.map((entry) => (
            <View key={entry.question} style={styles.block}>
              <Text style={styles.groupTitle}>Q: {entry.question}</Text>
              {entry.answers.map((answer, answerIndex) => (
                <Text key={`${entry.question}-${answerIndex}`} style={styles.bullet}>"{answer}"</Text>
              ))}
            </View>
          ))}
        </View>
      ) : null}
    </Page>
  </Document>
  );
};
